#!/usr/bin/env bun
// export-svgs — export the diagrams of docs/nrs-pipeline.html as standalone
// SVG files for docs/nrs-pipeline.md, one light and one dark per diagram.
//
// The HTML is the source: each diagram is an inline <svg id="d-…" class="dg">
// whose classes are styled by the page's `svg.dg …` rules through CSS
// variables, so the page's theme toggle drives them. A standalone SVG shown by
// GitHub through <img> can't see the page's variables, so each file gets its
// own <style>: the same rules with every var(--x) replaced by that theme's
// value. The Markdown picks the file with <picture> and prefers-color-scheme,
// which GitHub ties to the reader's GitHub theme.
//
// Run after changing a diagram or the palette, from anywhere:
//
//   bun docs/nrs-pipeline/export-svgs.ts
//
// It writes docs/nrs-pipeline/<name>.light.svg and <name>.dark.svg, where
// <name> is the diagram id without its "d-" prefix.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const here = import.meta.dir;
const htmlPath = join(dirname(here), "nrs-pipeline.html");
const repo = dirname(dirname(here));

function must(match: RegExpMatchArray | null, what: string): RegExpMatchArray {
  if (!match) {
    console.error(`export-svgs: ${what} not found in ${htmlPath}`);
    process.exit(1);
  }
  return match;
}

const html = readFileSync(htmlPath, "utf8");
const style = must(html.match(/<style>([\s\S]*?)<\/style>/), "<style> block")[1];

// The --name: value pairs of the first CSS block for `selector`.
function palette(selector: string): Map<string, string> {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const block = must(style.match(new RegExp(escaped + "\\s*\\{([\\s\\S]*?)\\}")), `${selector} palette`)[1];
  return new Map([...block.matchAll(/--([a-z-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2]]));
}

const themes = {
  light: palette(":root"),
  dark: palette(':root[data-theme="dark"]'),
};

// The page's diagram rules (whole rules; some span lines), re-scoped from
// `svg.dg` to the file's own root svg. Comments go first: one mentions
// `svg.dg`. The bare `svg.dg { … }` rule is page layout (block, full width)
// and has no place in a standalone file.
const rules = [...style.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/(svg\.dg[^{]*)\{([^}]*)\}/g)]
  .filter(([, selector]) => selector.trim() !== "svg.dg")
  .map(([, selector, body]) => `svg${selector.slice("svg.dg".length)}{${body.split(/\s+/).join(" ").trim()}}`)
  .join("\n");

function themed(theme: keyof typeof themes): string {
  const values = themes[theme];
  return rules.replace(/var\(--([a-z-]+)\)/g, (_, name: string) => {
    const value = values.get(name);
    if (value === undefined) {
      console.error(`export-svgs: --${name} is not in the ${theme} palette`);
      process.exit(1);
    }
    return value;
  });
}

const diagrams = [...html.matchAll(/<svg id="d-([a-z-]+)" class="dg"([^>]*)>([\s\S]*?)<\/svg>/g)];
if (diagrams.length === 0) {
  console.error('export-svgs: no <svg id="d-…" class="dg"> diagrams found');
  process.exit(1);
}

for (const [, name, attrs, body] of diagrams) {
  const [, width, height] = must(attrs.match(/viewBox="0 0 (\d+) (\d+)"/), `viewBox of d-${name}`);
  const label = must(attrs.match(/aria-label="([^"]*)"/), `aria-label of d-${name}`)[1];
  for (const theme of Object.keys(themes) as (keyof typeof themes)[]) {
    const out = join(here, `${name}.${theme}.svg`);
    writeFileSync(
      out,
      `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" ` +
        `viewBox="0 0 ${width} ${height}" role="img" aria-label="${label}">\n` +
        `<!-- Generated by docs/nrs-pipeline/export-svgs.ts from docs/nrs-pipeline.html ` +
        `(${theme} theme). Edit the HTML, not this file. -->\n` +
        `<style>\n${themed(theme)}\n</style>${body}</svg>\n`,
    );
    console.log(`wrote ${relative(repo, out)}`);
  }
}
