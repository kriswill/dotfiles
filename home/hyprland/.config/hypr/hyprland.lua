-- Hyprland config for nebula — entry point.
--
-- The actual configuration is split by concept into sibling modules, required
-- below in load order. Hyprland resolves require() against ~/.config/hypr/, and
-- every file there is a symlink into the dotfiles stow tree
-- (home/hyprland/.config/hypr/). Edit the modules, then `hyprctl reload`.
--
-- Wiki: https://wiki.hypr.land/Configuring/Start/  (Lua hl.* API, 0.55+)
--
-- Module map:
--   monitors      — display layout (hl.monitor)
--   programs      — terminal/file-manager/menu (shared table, used by keybindings)
--   autostart     — hl.on("hyprland.start", …)
--   environment   — env vars, XWayland scaling, permissions
--   look-and-feel — general/decoration/layouts/misc (hl.config)
--   animations    — bezier/spring curves + per-leaf animations
--   input         — keyboard/touchpad/gestures/devices
--   keybindings   — all binds (requires "programs")
--   window-rules  — window + layer rules

require("monitors")
require("autostart")
require("environment")
require("look-and-feel")
require("animations")
require("input")
require("keybindings")
require("window-rules")

-- Dux Shell color fragment — load LAST so its hl.config border colors win over
-- look-and-feel.lua. dms/colors.lua is GENERATED by Dux Shell's matugen pass
-- (~/.config/hypr/dms/, not tracked in this repo), so it can legitimately be
-- absent: fresh setup, shell not yet run, or shell disabled. require() on a
-- missing module is a hard error that would break the WHOLE config (this is the
-- failure that blanked the OLED on a bad reload), so gate it with
-- package.searchpath — it resolves "dms.colors" exactly like require would
-- (Hyprland sets package.path to ~/.config/hypr/?.lua; the dot maps to dms/),
-- returning the file path if present or nil if not, so an absent file is skipped
-- cleanly instead of erroring.
--
-- Only the colors fragment is used. Dux's other fragments (outputs, layout,
-- input, binds, windowrules) would fight monitors.lua / look-and-feel.lua /
-- input.lua / keybindings.lua, which own those here. NEVER run `dms setup`: it
-- rewrites this file, which is a stow symlink into the dotfiles repo.
-- (Noctalia, disabled since 2026-11-03, used the same gate on its generated
-- noctalia.lua + require("noctalia").apply_theme(); see docs/dux-shell.md.)
if package.searchpath("dms.colors", package.path) then
  require("dms.colors")
end

-- Our tweaks on top of the shell's generated theme — must load LAST so they win.
require("noctalia-overrides")
